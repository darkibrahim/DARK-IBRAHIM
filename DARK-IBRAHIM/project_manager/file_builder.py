"""Validate, brand and write generated project files."""
from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Tuple

import config
from security.validator import ValidationError, safe_relative_path

BRAND_LINE = (
    f"Generated by {config.APP_NAME} | Developer: {config.BRAND['developer']} | {config.BRAND['github']}"
)

_GITIGNORE = {
    "python": "__pycache__/\n*.pyc\n.venv/\nvenv/\n.env\n*.log\n.idea/\n.vscode/\n",
    "android": "*.iml\n.gradle/\nbuild/\nlocal.properties\n.idea/\n*.apk\n*.keystore\n*.jks\n",
    "web": "node_modules/\n.env\n*.log\n.DS_Store\n",
}

_RUN_HELP = {
    "python-cli": "```bash\npython main.py --help\n```",
    "flask-web": "```bash\npip install -r requirements.txt\npython app.py\n```\nThen open http://127.0.0.1:5000",
    "static-website": "Open `index.html` in a browser, or run `python -m http.server 8000`.",
    "android-app": (
        "The web app lives in `www/`. The `android/` folder is a ready Android Studio project.\n"
        "Build the APK with Android Studio, or push to GitHub and run the *Build APK* workflow."
    ),
}


def default_readme(plan: Dict) -> str:
    return (
        f"# {plan.get('title') or plan['name']}\n\n{plan['description']}\n\n"
        f"## Run\n\n{_RUN_HELP.get(plan['project_type'], '')}\n\n"
        f"## Author\n\n```\n{config.brand_block()}\n```\n\n"
        f"_Built with {config.APP_NAME} v{config.VERSION}._\n"
    )


def sanitize_files(files: Dict[str, str]) -> Tuple[Dict[str, str], List[str]]:
    """Drop files with unsafe paths, wrong types or too large content."""
    clean: Dict[str, str] = {}
    warnings: List[str] = []
    for raw_path, content in files.items():
        try:
            path = safe_relative_path(raw_path)
        except ValidationError as exc:
            warnings.append(f"Skipped file: {exc}")
            continue
        if not isinstance(content, str):
            warnings.append(f"Skipped {path}: content is not text")
            continue
        if len(content.encode("utf-8")) > config.MAX_FILE_BYTES:
            warnings.append(f"Skipped {path}: file too large")
            continue
        if len(clean) >= config.MAX_FILES + 25:
            warnings.append(f"Skipped {path}: too many files")
            continue
        clean[path] = content.replace("\r\n", "\n")
    return clean, warnings


def ensure_base_files(files: Dict[str, str], plan: Dict) -> None:
    kind = plan["project_type"]
    if "README.md" not in files:
        files["README.md"] = default_readme(plan)
    elif config.BRAND["developer"] not in files["README.md"]:
        files["README.md"] = files["README.md"].rstrip() + f"\n\n## Author\n\n```\n{config.brand_block()}\n```\n"
    if ".gitignore" not in files:
        group = "python" if kind in ("python-cli", "flask-web") else "web"
        files[".gitignore"] = _GITIGNORE[group] + (_GITIGNORE["android"] if kind == "android-app" else "")
    if kind in ("python-cli", "flask-web") and "requirements.txt" not in files:
        files["requirements.txt"] = "Flask>=3.0\n" if kind == "flask-web" else "# No third-party packages needed.\n"


def apply_branding(files: Dict[str, str]) -> None:
    for path, content in list(files.items()):
        if BRAND_LINE in content:
            continue
        if path.endswith((".py", ".sh")):
            lines = content.split("\n")
            at = 1 if lines and lines[0].startswith("#!") else 0
            lines.insert(at, f"# {BRAND_LINE}")
            files[path] = "\n".join(lines)


def write_files(root: Path, files: Dict[str, str]) -> List[Path]:
    root = root.resolve()
    written: List[Path] = []
    for raw_path, content in files.items():
        rel = safe_relative_path(raw_path)
        target = (root / rel).resolve()
        if root not in target.parents:
            raise ValidationError(f"Path escapes project folder: {raw_path!r}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        if rel.endswith(".sh"):
            target.chmod(0o755)
        written.append(target)
    return written
